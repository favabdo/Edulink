-- ============================================================================
--  EduLink — إنشاء قاعدة المنصة وكل جداولها على SQL Server (ملف واحد يعمل Run)
-- ============================================================================
-- هذا الملف مُستخرَج آليًا من database/schema.sql (قسم SQL Server في آخره).
-- **لا يُحرَّر يدويًا أبدًا**: أي تغيير في الجداول يُكتب في database/schema.sql
-- ثم يُعاد توليد هذا الملف بنفس الاستخراج المستخدَم في deploy/run.sh (دالة
-- extract_sqlserver) — والأمر مكتوب أيضًا في apps/api/README.md.
--
-- تراكمي ومحمي بـ IF NOT EXISTS / DROP ... IF EXISTS: يُشغَّل مرة أو عشر مرات بنفس النتيجة.
-- مُهيّأ لـ SQL Server 2014 وما بعدها: لا CREATE OR ALTER، لا تريجرات DML، لا فهرس على عمود MAX.
--
-- الاستخدام — من SSMS: افتح الملف كاملاً ثم Execute. أو من الطرفية (عدّل السيرفر والدخول):
--   sqlcmd -S "SERVER,1433" -U sa -P "PASSWORD" -f 65001 -I -b -i RUN-ON-SQL-SERVER.sql
--   sqlcmd -S "SERVER,1433" -U sa -P "PASSWORD" -d EdulinkDb -Q "SELECT tables=(SELECT COUNT(*) FROM sys.tables), triggers=(SELECT COUNT(*) FROM sys.triggers), checks=(SELECT COUNT(*) FROM sys.check_constraints), fks=(SELECT COUNT(*) FROM sys.foreign_keys)"
--
-- الأعلام ليست ترفًا: 65001 تقرأ الملف UTF-8 (بلاها تُخزَّن العربية ?)، و-I تُفعّل
-- QUOTED_IDENTIFIER (بلاها يرفض المحرّك INSERT/DELETE على جداول Edu_ لأن عليها فهارس
-- مفلترة — Msg 1934)، و-b يجعل أي خطأ يخرج بكود غير صفري بدل الصمت.
--
-- البصمة المتوقعة بعد التشغيل (مقيسة 2026-10-22): 11 جدولًا · صفر تريجر · 21 فحصًا ·
-- 9 مفاتيح خارجية · 43 قيمة افتراضية · 8 قيود تفريد · 107 أعمدة — منها 3 أعمدة `phone`
-- (المدرس/المشرف في Edu_Users، الطالب، ولي الأمر) و3 فهارس تفريد مفلترة
-- uq_edu_users_phone / uq_edu_students_phone / uq_edu_parents_phone (الرقم لا يتكرّر،
-- وNULL و'' مستثنيان لأن الفهارس مفلترة — لا تدخل في عداد «8 قيود تفريد» لأن نوعها
-- فهرس لا key constraint).
--
-- هذا الملف لا يُنشئ حساب دخول ولا يلمس صلاحيات: يُنشئ القاعدة EdulinkDb والجداول فقط.
-- إنشاء Login مخصّص للمنصة (أمنع من sa) خطوة منفصلة موثّقة في docs/06-deployment.md.
-- ============================================================================

-- (1) غيّر اسم القاعدة مرة واحدة هنا فقط: في السطرين التاليين معًا
IF DB_ID(N'EdulinkDb') IS NULL
